import { execFileSync } from 'node:child_process';
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const config = JSON.parse(readFileSync('src-tauri/tauri.conf.json', 'utf8'));
const version = process.argv[2] || JSON.parse(readFileSync('package.json', 'utf8')).version;
if (!/^\d+\.\d+\.\d+$/.test(version)) {
  throw new Error('Usage: node scripts/create-arch-pkg.mjs 1.2.3');
}

const binaryPath = 'src-tauri/target/release/db-sync-ssh';
if (!existsSync(binaryPath)) {
  throw new Error(`Release binary not found: ${binaryPath}`);
}

const appName = (config.productName || 'DB Sync Engine SSH').replace(/\s+/g, '.');
const packageName = `DB.Sync.Engine.SSH-${version}-x86_64.pkg.tar.zst`;
const stageDir = mkdtempSync(path.join(os.tmpdir(), 'db-sync-ssh-pkg-'));
const desktopDir = path.join(stageDir, 'usr/share/applications');

try {
  mkdirSync(path.join(stageDir, 'usr/bin'), { recursive: true });
  mkdirSync(desktopDir, { recursive: true });

  cpSync(binaryPath, path.join(stageDir, 'usr/bin/db-sync-ssh'));
  writeFileSync(
    path.join(desktopDir, 'db-sync-ssh.desktop'),
    `[Desktop Entry]
Name=${config.productName || 'DB Sync Engine SSH'}
Comment=Synchronize MySQL and MariaDB databases over SSH
Exec=db-sync-ssh
Icon=db-sync-ssh
StartupWMClass=db-sync-ssh
Terminal=false
Type=Application
Categories=Development;Database;Utility;
`,
  );

  for (const [size, filename] of [
    ['128x128', '128x128.png'],
    ['32x32', '32x32.png'],
  ]) {
    const source = path.join('src-tauri/icons', filename);
    if (!existsSync(source)) continue;
    const destination = path.join(
      stageDir,
      `usr/share/icons/hicolor/${size}/apps/db-sync-ssh.png`,
    );
    mkdirSync(path.dirname(destination), { recursive: true });
    cpSync(source, destination);
  }

  const binarySize = statSync(path.join(stageDir, 'usr/bin/db-sync-ssh')).size;
  writeFileSync(
    path.join(stageDir, '.PKGINFO'),
    `# Generated by create-arch-pkg.mjs
pkgname = db-sync-ssh
pkgbase = db-sync-ssh
pkgver = ${version}-1
pkgdesc = DB Sync Engine - MySQL/MariaDB over SSH
url = https://github.com/HeriEfendi/DB-Sync-Ssh
builddate = ${Math.floor(Date.now() / 1000)}
packager = Release Bot <noreply@github.com>
size = ${binarySize}
arch = x86_64
license = MIT
depend = webkit2gtk-4.1
depend = gtk3
depend = cairo
depend = hicolor-icon-theme
depend = openssl
depend = libssh2
provides = db-sync-ssh
conflicts = db-sync-ssh
`,
  );

  execFileSync(
    'tar',
    [
      '--zstd',
      '-cf',
      packageName,
      '--owner=0',
      '--group=0',
      '-C',
      stageDir,
      '.PKGINFO',
      'usr',
    ],
    { stdio: 'inherit' },
  );
} finally {
  rmSync(stageDir, { recursive: true, force: true });
}

console.log(`Created Arch Linux package ${packageName} for ${appName}.`);
